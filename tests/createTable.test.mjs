import assert from "node:assert/strict";
import { DatabaseSync } from "node:sqlite";
import test from "node:test";
import { buildCreateTableStatements, COLUMN_TYPES, validateTableDefinition } from "../src/utils/createTable.ts";

const id = { name: "id", type: "INTEGER", pk: true, notNull: true };
const value = { name: "value", type: "TEXT", pk: false, notNull: false };

test("SQLite creates defaults and automatically updates only the changed row with recursive triggers enabled", () => {
  const db = new DatabaseSync(":memory:");
  try {
    db.exec("PRAGMA recursive_triggers = ON");
    for (const sql of buildCreateTableStatements("sqlite", 'Mixed"Case', [id, value], true)) db.exec(sql);
    db.exec(`INSERT INTO "Mixed""Case" (value) VALUES ('first'), ('second')`);
    const before = db.prepare(`SELECT * FROM "Mixed""Case" ORDER BY id`).all();
    assert.match(before[0].created_at, /^\d{4}-\d{2}-\d{2} /);
    assert.equal(before[0].created_at, before[0].updated_at);
    db.exec(`UPDATE "Mixed""Case" SET updated_at = '2000-01-01 00:00:00'`);
    db.exec(`UPDATE "Mixed""Case" SET id = 3, value = 'changed' WHERE id = 1`);
    const after = db.prepare(`SELECT * FROM "Mixed""Case" ORDER BY id`).all();
    assert.equal(after[0].id, 2);
    assert.equal(after[0].updated_at, "2000-01-01 00:00:00");
    assert.equal(after[1].id, 3);
    assert.equal(after[1].created_at, before[0].created_at);
    assert.ok(after[1].updated_at > "2000-01-01 00:00:00");
    // Repeated writes in the same second must terminate when recursion is on.
    db.exec(`UPDATE "Mixed""Case" SET value = 'changed again' WHERE id = 3`);
    assert.equal(db.prepare(`SELECT value FROM "Mixed""Case" WHERE id = 3`).get().value, "changed again");
  } finally {
    db.close();
  }
});

test("SQLite timestamp triggers handle composite keys, text keys, and tables without a primary key", () => {
  for (const columns of [
    [id, { ...value, pk: true }],
    [{ ...id, type: "TEXT" }, value],
    [{ ...value, name: "rowid" }],
  ]) {
    const db = new DatabaseSync(":memory:");
    try {
      db.exec("PRAGMA recursive_triggers = ON");
      for (const sql of buildCreateTableStatements("sqlite", "entries", columns, true)) db.exec(sql);
      if (columns.length === 1) db.exec("INSERT INTO entries (rowid) VALUES ('first'), ('second')");
      else db.exec("INSERT INTO entries (id, value) VALUES ('1', 'first'), ('2', 'second')");
      db.exec("UPDATE entries SET updated_at = '2000-01-01 00:00:00'");
      const field = columns.length === 1 ? "rowid" : "value";
      db.exec(`UPDATE entries SET ${field} = 'changed' WHERE ${field} = 'first'`);
      assert.ok(db.prepare(`SELECT updated_at FROM entries WHERE ${field} = 'changed'`).get().updated_at > "2000-01-01 00:00:00");
      assert.equal(db.prepare(`SELECT updated_at FROM entries WHERE ${field} = 'second'`).get().updated_at, "2000-01-01 00:00:00");
    } finally {
      db.close();
    }
  }
});

test("MySQL timestamps use native defaults and ON UPDATE, with escaped identifiers", () => {
  const statements = buildCreateTableStatements("mysql", "Mixed`Case", [id, value], true);
  assert.equal(statements.length, 1);
  assert.match(statements[0], /CREATE TABLE `Mixed``Case`/);
  assert.match(statements[0], /`created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,/);
  assert.match(statements[0], /`updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP/);
});

test("primary key types and composite primary keys retain their declared meaning", () => {
  for (const dialect of Object.keys(COLUMN_TYPES)) {
    const textSql = buildCreateTableStatements(dialect, "Entries", [{ ...id, type: "VARCHAR(255)" }], false)[0];
    assert.match(textSql, /VARCHAR\(255\)/);
    assert.doesNotMatch(textSql, /AUTO_INCREMENT|AUTOINCREMENT|SERIAL|IDENTITY/);
    const compositeSql = buildCreateTableStatements(dialect, "Entries", [id, { ...value, pk: true }], false)[0];
    assert.equal((compositeSql.match(/PRIMARY KEY/g) ?? []).length, 1);
    assert.doesNotMatch(compositeSql, /AUTO_INCREMENT|AUTOINCREMENT|IDENTITY/);
  }
  assert.match(buildCreateTableStatements("postgres", "Entries", [id], false)[0], /INTEGER GENERATED BY DEFAULT AS IDENTITY/);
  assert.doesNotMatch(buildCreateTableStatements("sqlite", "Entries", [{ ...id, type: "BIGINT" }], false)[0], /AUTOINCREMENT/);
});

test("timestamp SQL uses native types and trigger syntax for PostgreSQL, Oracle, and SQL Server", () => {
  const postgres = buildCreateTableStatements("postgres", "Entries", [id], true);
  assert.equal(postgres.length, 3);
  assert.match(postgres[1], /RETURNS TRIGGER/);
  assert.match(postgres[1], /NEW\."updated_at" := CURRENT_TIMESTAMP/);
  assert.match(postgres[2], /BEFORE UPDATE ON "Entries"/);
  const oracle = buildCreateTableStatements("oracle", "Entries", [id], true);
  assert.match(oracle[0], /"created_at" TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL/);
  assert.match(oracle[1], /:NEW\."updated_at" := CURRENT_TIMESTAMP/);
  const mssql = buildCreateTableStatements("mssql", "Entries]", [id, { ...value, pk: true }], true);
  assert.match(mssql[0], /CREATE TABLE \[Entries\]\]/);
  assert.match(mssql[0], /\[updated_at\] DATETIME2 NOT NULL DEFAULT CURRENT_TIMESTAMP/);
  assert.match(mssql[1], /IF UPDATE\(\[updated_at\]\) RETURN/);
  assert.match(mssql[1], /target\.\[id\] = source\.\[id\] AND target\.\[value\] = source\.\[value\]/);
});

test("PostgreSQL timestamp setup reuses the function left behind after dropping a table", () => {
  const first = buildCreateTableStatements("postgres", "Entries", [id], true);
  const recreated = buildCreateTableStatements("postgres", "Entries", [{ ...id, type: "UUID" }, value], true);
  assert.match(recreated[1], /^CREATE OR REPLACE FUNCTION /);
  assert.equal(recreated[1], first[1]);
  assert.equal(recreated[2], first[2]);
});

test("validation prevents duplicate generated columns and unsupported timestamp row matching", () => {
  assert.equal(validateTableDefinition("mysql", "entries", [id, value], true), null);
  assert.match(validateTableDefinition("mysql", "entries", [id, { ...value, name: "CREATED_AT" }], true), /added automatically/);
  assert.match(validateTableDefinition("sqlite", "entries", [id, { ...value, name: "ID" }], false), /unique/);
  assert.match(validateTableDefinition("mssql", "entries", [value], true), /primary key/);
  assert.equal(validateTableDefinition("mssql", "entries", [value], false), null);
  const hiddenRowIds = ["rowid", "_rowid_", "oid"].map(name => ({ ...value, name }));
  assert.match(validateTableDefinition("sqlite", "entries", hiddenRowIds, true), /primary key/);
  assert.equal(validateTableDefinition("sqlite", "entries", [{ ...hiddenRowIds[0], pk: true }, ...hiddenRowIds.slice(1)], true), null);
});
